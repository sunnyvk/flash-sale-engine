-- booking_db: owned exclusively by booking-service. No other service reads these tables.

CREATE TABLE flash_events (
    id          BIGINT         NOT NULL AUTO_INCREMENT,
    name        VARCHAR(200)   NOT NULL,
    starts_at   DATETIME(3)    NOT NULL,
    total_seats INT            NOT NULL,
    price       DECIMAL(10, 2) NOT NULL,
    created_at  DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT chk_event_total_seats CHECK (total_seats > 0),
    CONSTRAINT chk_event_price CHECK (price >= 0)
) ENGINE = InnoDB;

-- One row per physical seat. Contention happens on these rows, which is exactly what we want to demonstrate.
CREATE TABLE seats (
    id          BIGINT      NOT NULL AUTO_INCREMENT,
    event_id    BIGINT      NOT NULL,
    seat_number VARCHAR(16) NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE',
    held_by     VARCHAR(64) NULL,
    held_until  DATETIME(3) NULL,
    version     BIGINT      NOT NULL DEFAULT 0, -- used by the optimistic-locking variant in phase 2
    PRIMARY KEY (id),
    UNIQUE KEY uq_seat_event_number (event_id, seat_number),
    KEY idx_seat_event_status (event_id, status, id),      -- "give me any available seat" (SKIP LOCKED scan)
    KEY idx_seat_status_held_until (status, held_until),   -- hold-expiry reaper (phase 5)
    CONSTRAINT fk_seat_event FOREIGN KEY (event_id) REFERENCES flash_events (id),
    CONSTRAINT chk_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED')),
    -- A HELD seat must say who holds it and until when; otherwise the reaper could never release it.
    CONSTRAINT chk_seat_held CHECK (status <> 'HELD' OR (held_by IS NOT NULL AND held_until IS NOT NULL))
) ENGINE = InnoDB;

CREATE TABLE bookings (
    id              CHAR(36)       NOT NULL,           -- UUID generated by the app: non-enumerable, usable as saga correlation id
    user_id         VARCHAR(64)    NOT NULL,
    event_id        BIGINT         NOT NULL,
    seat_id         BIGINT         NOT NULL,
    status          VARCHAR(20)    NOT NULL,           -- PENDING_PAYMENT -> CONFIRMED | CANCELLED | EXPIRED
    amount          DECIMAL(10, 2) NOT NULL,
    idempotency_key VARCHAR(64)    NOT NULL,
    failure_reason  VARCHAR(255)   NULL,
    created_at      DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),

    -- THE oversell backstop. MySQL has no partial unique index, so we emulate one: this column equals seat_id
    -- while the booking is "live" and NULL once it is cancelled/expired. A UNIQUE index ignores NULLs, so a seat
    -- can have many dead bookings but at most ONE live one. Whatever the app or Redis does, the DB refuses a double-book.
    active_seat_id  BIGINT GENERATED ALWAYS AS (
        CASE WHEN status IN ('PENDING_PAYMENT', 'CONFIRMED') THEN seat_id ELSE NULL END
    ) STORED,

    PRIMARY KEY (id),
    UNIQUE KEY uq_booking_active_seat (active_seat_id),
    -- Last line of defence for idempotency if Redis loses a key (phase 3): same user + same key = same booking.
    UNIQUE KEY uq_booking_user_idempotency (user_id, idempotency_key),
    KEY idx_booking_user_created (user_id, created_at),
    CONSTRAINT fk_booking_event FOREIGN KEY (event_id) REFERENCES flash_events (id),
    CONSTRAINT fk_booking_seat FOREIGN KEY (seat_id) REFERENCES seats (id),
    CONSTRAINT chk_booking_status CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
) ENGINE = InnoDB;

-- Transactional outbox (phase 4): written in the SAME transaction as the state change, relayed to Kafka afterwards.
CREATE TABLE outbox_events (
    id             BIGINT      NOT NULL AUTO_INCREMENT,  -- monotonic: the relay publishes in id order
    event_id       CHAR(36)    NOT NULL,                 -- stable id consumers use to de-duplicate
    aggregate_type VARCHAR(32) NOT NULL,
    aggregate_id   VARCHAR(64) NOT NULL,                 -- becomes the Kafka message key => per-booking ordering
    event_type     VARCHAR(64) NOT NULL,
    payload        JSON        NOT NULL,
    status         VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    published_at   DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_outbox_event_id (event_id),
    KEY idx_outbox_status_id (status, id),
    CONSTRAINT chk_outbox_status CHECK (status IN ('PENDING', 'PUBLISHED'))
) ENGINE = InnoDB;

-- Consumer-side dedupe: Kafka delivery is at-least-once, so handlers must tolerate seeing an event twice.
CREATE TABLE processed_events (
    event_id     CHAR(36)    NOT NULL,
    processed_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (event_id)
) ENGINE = InnoDB;
